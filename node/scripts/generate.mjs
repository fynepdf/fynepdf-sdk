// Writes src/generated.ts from the API's own OpenAPI document and action catalog
// (../spec, exported by the API). Run after the spec changes: npm run generate.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "..", "spec", "openapi.json"), "utf8"));
const catalog = JSON.parse(readFileSync(join(root, "..", "spec", "catalog.json"), "utf8"));

const pascal = (s) => s.replace(/(^|[_-])([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const SHORTCUT_BASE = new Set(["file_id", "file_ids", "wait", "webhook_url", "metadata"]);

const doc = (text, indent) => {
  if (!text) return "";
  const lines = String(text).trim().split("\n");
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join("\n")}\n${indent} */\n`;
};

function ts(schema, indent = "") {
  if (!schema || Object.keys(schema).length === 0) return "unknown";
  if (schema.$ref) return schema.$ref.split("/").pop();
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (schema.allOf) return schema.allOf.map((s) => ts(s, indent)).join(" & ");
  const options = schema.anyOf ?? schema.oneOf;
  if (options) return options.map((s) => wrap(ts(s, indent))).join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map((t) => ts({ ...schema, type: t }, indent)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `Array<${ts(schema.items, indent)}>`;
    default:
      if (schema.properties) return objectType(schema, indent);
      if (schema.additionalProperties && schema.additionalProperties !== true)
        return `Record<string, ${ts(schema.additionalProperties, indent)}>`;
      return "Record<string, unknown>";
  }
}

const wrap = (type) => (type.includes(" & ") || type.includes("{") ? `(${type})` : type);

function objectType(schema, indent, skip = new Set()) {
  const required = new Set(schema.required ?? []);
  const inner = `${indent}  `;
  const fields = Object.entries(schema.properties ?? {})
    .filter(([key]) => !skip.has(key))
    .map(([key, value]) => {
      const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
      return `${doc(value.description, inner)}${inner}${name}${required.has(key) ? "" : "?"}: ${ts(value, inner)};`;
    });
  return fields.length ? `{\n${fields.join("\n")}\n${indent}}` : "Record<string, never>";
}

const out = [
  "// Generated by scripts/generate.mjs from the FynePDF OpenAPI document. Don't edit by hand.",
  "/* eslint-disable */",
  "",
];

// Named schemas: Job, File, Problem, ...
for (const [name, schema] of Object.entries(spec.components.schemas)) {
  out.push(`${doc(schema.description, "")}export type ${name} = ${ts(schema)};`, "");
}

// Request and response types for every operation that isn't an action shortcut.
for (const [path, methods] of Object.entries(spec.paths)) {
  if (path.startsWith("/pdf/")) continue;
  for (const op of Object.values(methods)) {
    const name = pascal(op.operationId);
    const body = op.requestBody?.content?.["application/json"]?.schema;
    if (body) out.push(`/** Body of \`${op.operationId}\`. */`, `export type ${name}Request = ${ts(body)};`, "");
    const ok = Object.entries(op.responses).find(([status]) => status.startsWith("2"))?.[1];
    const response = ok?.content?.["application/json"]?.schema;
    if (response) out.push(`/** What \`${op.operationId}\` answers. */`, `export type ${name}Response = ${ts(response)};`, "");
  }
}

// One typed method per action: its parameters, and how it takes files.
const methods = [];
const routes = [];
for (const action of catalog.actions) {
  const path = action.shortcut.path.replace(/^\/v1/, "");
  const op = spec.paths[path]?.post;
  const schema = op?.requestBody?.content?.["application/json"]?.schema;
  if (!schema) continue;
  const type = `${pascal(action.name)}Params`;
  out.push(`${doc(`Parameters of \`${action.name}\` (${action.title}).`, "")}export type ${type} = ${objectType(schema, "", SHORTCUT_BASE)};`, "");
  const input = !action.accepts.length ? "NoInput" : action.combines ? "ManyFiles" : "OneFile";
  const method = camel(action.name);
  methods.push(
    `${doc(`${action.title}: ${action.description}\n\nPrice: ${action.credits}. Takes ${action.accepts.length ? action.accepts.join(", ") : "no input file"}; makes ${action.output}.\n@see https://fynepdf.com/developers/docs/api/${path.replace("/pdf/", "")}`, "  ")}  ${method}(params: ${input} & ${type} & JobOptions): Promise<Job>;`,
  );
  routes.push(`  ${method}: "${path}",`);
}

out.push(
  "/** Input for actions that take one file. */",
  "export type OneFile = { file_id: string };",
  "/** Input for actions that take every file given (merge, image_to_pdf). */",
  "export type ManyFiles = { file_ids: string[] };",
  "/** Actions that make a file from nothing (create_pdf, html_to_pdf). */",
  "export type NoInput = {};",
  "",
  "/** How a job runs and reports back. */",
  "export interface JobOptions {",
  "  /** Seconds to wait for the result in the call (0 to 60; default 30 for actions). */",
  "  wait?: number;",
  "  /** Told when the job ends (Standard Webhooks signatures). */",
  "  webhook_url?: string;",
  "  /** Your own keys and values, returned on the job and in webhooks. */",
  "  metadata?: Record<string, string>;",
  "}",
  "",
  "/** Every PDF action as one call. Each is a one-step job, waited for up to `wait` seconds. */",
  "export interface PdfActions {",
  ...methods,
  "}",
  "",
  "export const ACTION_ROUTES: Record<keyof PdfActions, string> = {",
  ...routes,
  "};",
  "",
);

writeFileSync(join(root, "src", "generated.ts"), out.join("\n"));
console.log(`src/generated.ts: ${Object.keys(spec.components.schemas).length} schemas, ${methods.length} actions`);
