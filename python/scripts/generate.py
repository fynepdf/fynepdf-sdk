"""Writes src/fynepdf/_generated.py from the API's OpenAPI document and action catalog (../spec).

Run after the spec changes:  python scripts/generate.py
"""

from __future__ import annotations

import json
import keyword
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT.parent / "spec" / "openapi.json").read_text(encoding="utf-8"))
CATALOG = json.loads((ROOT.parent / "spec" / "catalog.json").read_text(encoding="utf-8"))
SHORTCUT_BASE = {"file_id", "file_ids", "wait", "webhook_url", "metadata"}


def py_type(schema: dict | None) -> str:
    if not schema:
        return "Any"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return f"Literal[{json.dumps(schema['const'])}]"
    if "enum" in schema:
        return f"Literal[{', '.join(json.dumps(v) for v in schema['enum'])}]"
    if "allOf" in schema:
        return "dict[str, Any]"
    options = schema.get("anyOf") or schema.get("oneOf")
    if options:
        return " | ".join(dict.fromkeys(py_type(s) for s in options))
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(py_type({**schema, "type": t}) for t in kind)
    return {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "null": "None",
    }.get(kind, "list[" + py_type(schema.get("items")) + "]" if kind == "array" else "dict[str, Any]")


def doc(text: str, indent: str) -> str:
    lines = text.strip().replace('"""', "'''").splitlines()
    body = "\n".join(f"{indent}{line}".rstrip() for line in lines)
    return f'{indent}"""{body.lstrip()}\n{indent}"""\n'


out = [
    '"""Generated by scripts/generate.py from the FynePDF OpenAPI document. Don\'t edit by hand."""',
    "",
    "from __future__ import annotations",
    "",
    "from typing import TYPE_CHECKING, Any, Literal, TypedDict",
    "",
    "if TYPE_CHECKING:",
    "    from ._client import FynePDF",
    "",
    "",
]

# Named schemas as TypedDicts (every field optional: the API may add fields).
for name, schema in SPEC["components"]["schemas"].items():
    props = schema.get("properties", {})
    out.append(f"class {name}(TypedDict, total=False):")
    if schema.get("description"):
        out.append(doc(schema["description"], "    ").rstrip("\n"))
    if not props:
        out.append("    pass")
    for key, value in props.items():
        out.append(f"    {key}: {py_type(value)}")
    out.extend(["", ""])

# One method per action, with its parameters as real keyword arguments.
methods = []
for action in CATALOG["actions"]:
    path = action["shortcut"]["path"].removeprefix("/v1")
    op = SPEC["paths"].get(path, {}).get("post")
    schema = (op or {}).get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
    if not schema:
        continue
    required = set(schema.get("required", []))
    args = []
    if action["accepts"]:
        args.append("file_ids: list[str]" if action["combines"] else "file_id: str")
    params = [(k, v) for k, v in schema.get("properties", {}).items() if k not in SHORTCUT_BASE]
    for key, value in sorted(params, key=lambda kv: kv[0] not in required):
        name = f"{key}_" if keyword.iskeyword(key) else key
        args.append(f"{name}: {py_type(value)}" if key in required else f"{name}: {py_type(value)} | None = None")
    args += ["wait: int | None = None", "webhook_url: str | None = None", "metadata: dict[str, str] | None = None"]
    method = action["name"]
    names = [re.split(r"[:=]", a)[0].strip() for a in args]
    body = ", ".join(f'"{n.rstrip("_")}": {n}' for n in names)
    text = (
        f"{action['title']}: {action['description']}\n\n"
        f"Price: {action['credits']}. Takes {', '.join(action['accepts']) or 'no input file'}; makes {action['output']}.\n"
        f"https://fynepdf.com/developers/docs/api/{path.removeprefix('/pdf/')}"
    )
    methods.append(
        f"    def {method}(self, *, {', '.join(args)}) -> Job:\n"
        + doc(text, "        ")
        + f'        return self._client._post("{path}", {{{body}}})\n'
    )

out += [
    "class PdfActions:",
    '    """Every PDF action as one call (a one-step job, waited for up to `wait` seconds, 30 by default)."""',
    "",
    "    def __init__(self, client: FynePDF) -> None:",
    "        self._client = client",
    "",
    "\n".join(methods),
]

(ROOT / "src" / "fynepdf" / "_generated.py").write_text("\n".join(out), encoding="utf-8")
print(f"_generated.py: {len(SPEC['components']['schemas'])} schemas, {len(methods)} actions")
